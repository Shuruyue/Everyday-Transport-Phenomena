"""Generate synthetic CSVs from the [truth] tables of the synthetic configs.

    python scripts/make_synthetic_data.py

Purpose: run the whole analysis pipeline before any experiment, and check that
it recovers parameters it did not see. The data are produced with richer
models than the analysis fits (finer grid, temperature-dependent h, radiation,
true k different from the handbook value, true D different from Fuller) so the
recovery test is not circular. These files are NOT measurements.
"""

from __future__ import annotations

import numpy as np

from transport_phenomena_experiments import build
from transport_phenomena_experiments.constants import c_to_k
from transport_phenomena_experiments.correlations import h_forced_cylinder, h_free_horizontal_cylinder
from transport_phenomena_experiments.heat.fin_fv import Rod, SurfaceLoss
from transport_phenomena_experiments.heat.lumped import cool_lumped
from transport_phenomena_experiments.io import load_config, utf8_console, write_table
from transport_phenomena_experiments.mass import evaporation as ev
from transport_phenomena_experiments.mass import stefan
from transport_phenomena_experiments.mass.activity import ETHANOL_WATER_NRTL, Ideal
from transport_phenomena_experiments.properties import ETHANOL, WATER

HEADER = "SYNTHETIC DATA generated by scripts/make_synthetic_data.py - not a measurement"


def week1(cfg):
    tr = cfg["truth"]
    rng = np.random.default_rng(tr["seed"])
    T_inf, T_sur, P = build.environment(cfg["environment"])
    rods = {r["name"]: build.rod_spec(r) for r in cfg["rods"]}
    for run in cfg["heating"]:
        spec = rods[run["rod"]]
        k_true = spec.material.k * tr["k_factor"][spec.name]
        L = run["exposed_length_cm"] * build.CM
        a, p = spec.section_functions()
        rod = Rod(L, 300, a, p, k_true, spec.material.rho * spec.material.cp, "convective")
        loss = SurfaceLoss(lambda T, D=spec.diameter: tr["C_h_natural"]
                           * h_free_horizontal_cylinder(D, T, T_inf, P), T_inf, spec.eps, T_sur)
        t = np.arange(0.0, 1500.0 + 1e-9, 5.0)
        T_b = c_to_k(tr["T_base_C"])
        T0 = np.full(rod.x.size, T_inf)
        T0[0] = T_b
        Tn = rod.transient(t, lambda _: T_b, T0, loss)
        x_s = np.array(run["sensor_positions_cm"]) * build.CM
        sens = np.array([np.interp(x_s, rod.x, r) for r in Tn])
        cols = {"t_s": t, "T_base_C": T_b - 273.15 + rng.normal(0, tr["noise_K"], t.size)}
        for i in range(x_s.size):
            cols[f"T{i + 1}_C"] = sens[:, i] - 273.15 + rng.normal(0, tr["noise_K"], t.size)
        write_table(run["csv"], cols, HEADER)
    for run in cfg["cooling"]:
        spec = rods[run["rod"]]
        if run["mode"] == "natural":
            hc = lambda T, D=spec.diameter: tr["C_h_natural"] * h_free_horizontal_cylinder(  # noqa: E731
                D, T, T_inf, P)
            t_end = 2400.0
        else:
            U = tr["fan_U_m_s"][run["fan_label"]]
            hc = lambda T, D=spec.diameter, U=U: tr["C_h_forced"] * np.array(  # noqa: E731
                [h_forced_cylinder(D, U, Ti, T_inf, P, "churchill_bernstein") for Ti in np.atleast_1d(T)])
            t_end = 900.0
        t = np.arange(0.0, t_end + 1e-9, 5.0)
        T = cool_lumped(t, c_to_k(tr["T_start_cooling_C"]), spec.C, spec.A_surface,
                        SurfaceLoss(hc, T_inf, spec.eps, T_sur))
        write_table(run["csv"], {"t_s": t, "T_C": T - 273.15 + rng.normal(0, tr["noise_K"], t.size)},
                    HEADER)


def week2(cfg):
    tr = cfg["truth"]
    rng = np.random.default_rng(tr["seed"])
    amb = build.ambient(cfg["environment"])
    D_true = lambda T: tr["D_ethanol_25C_m2_s"] * (T / 298.15) ** 1.75  # noqa: E731
    from transport_phenomena_experiments.constants import R

    c = amb.P / (R * amb.T_inf)
    c_L = ETHANOL.rho(amb.T_inf) / ETHANOL.M
    y_s = ETHANOL.psat(amb.T_inf) / amb.P
    t_h = np.arange(0.0, tr["stefan_duration_h"] + 1e-9, tr["stefan_interval_h"])
    for st in cfg["stefan"]:
        A = np.pi * (st["inner_diameter_mm"] * build.MM) ** 2 / 4
        z0 = st["z0_mm"] * build.MM
        z = np.sqrt(z0**2 + stefan.stefan_slope(c, c_L, D_true(amb.T_inf), y_s, 0.0) * t_h * 3600)
        if st["reading"] == "mass":
            m = 25.0 - (z - z0) * ETHANOL.rho(amb.T_inf) * A * 1e3
            cols = {"t_h": t_h, "mass_g": m + rng.normal(0, tr["noise_mass_g"], t_h.size)}
        else:
            cols = {"t_h": t_h, "z_mm": z * 1e3 + rng.normal(0, tr["stefan_level_noise_mm"], t_h.size)}
        write_table(st["csv"], cols, HEADER)

    dc = cfg["dish"]
    R_d = dc["inner_diameter_mm"] * build.MM / 2
    diff = ev.Diffusivities(D_true, build.diffusivities({"source": "fuller"}, amb.P).water)
    for run in cfg["dish_runs"]:
        m0 = tr["initial_liquid_g"][run["name"]] * build.G
        if run["liquid"] == "ethanol":
            nE, nW, act, wx = m0 / ETHANOL.M, 0.0, Ideal(), False
        else:
            w = run["ethanol_mass_fraction"]
            nE, nW, act, wx = w * m0 / ETHANOL.M, (1 - w) * m0 / WATER.M, ETHANOL_WATER_NRTL, True
        V0 = nE * ETHANOL.M / ETHANOL.rho(amb.T_inf) + nW * WATER.M / WATER.rho(amb.T_inf)
        recess0 = dc["rim_height_mm"] * build.MM - V0 / (np.pi * R_d**2)
        dish = ev.Dish(R_d, recess0, dc["dish_mass_g"] * build.G * dc["dish_cp_J_per_kgK"],
                       tr["UA_bottom_W_per_K"], dc["eps_liquid"])
        if run["mode"] == "natural":
            model = ev.FreeConvectionSurface(dish.L_char, tr["multiplier"]["natural"], "raise")
        else:
            model = ev.ForcedFlatPlate(tr["U_m_s"][run["fan_label"]], 2 * R_d, tr["multiplier"]["forced"])
        t = np.arange(0.0, tr["duration_h"][run["name"]] * 3600 + 1e-9, 300.0)
        r = ev.simulate_evaporation(t, nE, nW, amb.T_inf, dish, amb, model, diff, act, wx, False,
                                    "stagnant_layer", 0.02)
        n = r.t.size
        cols = {"t_min": r.t / 60,
                "mass_g": dc["tare_g"] + r.mass * 1e3 + rng.normal(0, tr["noise_mass_g"], n),
                "T_liquid_C": r.T_s - 273.15 + rng.normal(0, tr["noise_T_K"], n)}
        write_table(run["csv"], cols, HEADER)


if __name__ == "__main__":
    utf8_console()
    week1(load_config("config/synthetic/week1.toml"))
    week2(load_config("config/synthetic/week2.toml"))
    print("synthetic CSVs written to data/synthetic/")
