"""Order-of-magnitude design numbers for both experiments (before any data).

    python scripts/design_estimates.py   -> docs/design_estimates.md

These are the numbers behind the sensor positions, sampling intervals and
container sizes in the experiment plans. Assumed set-up values are listed at
the top of each table; change them here and rerun.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from etp.constants import ATM, R, c_to_k
from etp.correlations import h_forced_cylinder, h_free_horizontal_cylinder, h_radiation
from etp.diffusivity import d_chapman_enskog, d_fuller
from etp.heat import fin
from etp.io import utf8_console
from etp.mass import evaporation as ev
from etp.mass import stefan
from etp.mass.activity import Ideal
from etp.properties import ETHANOL, MATERIALS, dew_point

utf8_console()
T_INF = c_to_k(25.0)
L = []

# ------------------------------------------------------------------ Week 1
D, L_exp, T_b = 4e-3, 0.15, c_to_k(100.0)
Ac, P = fin.pin_section(D)
h_nat = float(h_free_horizontal_cylinder(D, np.array([T_b]), T_INF, ATM)[0])
h_rad_bare = float(h_radiation(0.15, T_b, T_INF))
h = h_nat + h_rad_bare
L += ["# Design estimates", "", "Generated by `scripts/design_estimates.py`. Room air 25 °C, 1 atm.", "",
      "## Week 1: rod in boiling water", "",
      f"Rod diameter {D * 1e3:g} mm, {L_exp * 100:g} cm exposed, base 100 °C. "
      f"h = {h_nat:.1f} (Churchill-Chu at the base temperature) + {h_rad_bare:.1f} (radiation, bare metal "
      f"ε = 0.15) = {h:.1f} W/m²K, taken uniform.", "",
      "| material | k [W/m K] | 1/m [cm] | tip steady [°C] | q_base [W] | τ₁ to steady [s] |",
      "|---|---|---|---|---|---|"]
Lc = fin.corrected_length(L_exp, Ac, P)
for key in ("AISI_304", "AISI_430", "aluminum_6061_T6", "aluminum_pure", "copper_pure"):
    mat = MATERIALS[key]
    m = fin.fin_parameter(h, P, mat.k, Ac)
    tip = 25 + 75 * fin.theta_convective_tip(L_exp, L_exp, m, h, mat.k)
    q = fin.q_base_convective_tip(h, P, mat.k, Ac, L_exp, 75.0, h)
    tau = fin.slowest_time_constant(Lc, m, mat.alpha)
    L.append(f"| {mat.name} | {mat.k:g} | {100 / m:.1f} | {tip:.1f} | {q:.2f} | {tau:.0f} |")

mat = MATERIALS["AISI_304"]
C_per_A = mat.rho * mat.cp * D / 4  # lumped: V/A = D/4 for a long rod
T_mid = c_to_k(25 + 40)
L += ["", "Cooling of the whole stainless (304) rod from a uniform 100 °C (lumped, V/A = D/4). "
      "h evaluated at the mean excess temperature (ΔT = 40 K), radiation with ε = 0.3.", "",
      "| condition | h_conv [W/m²K] | h_total [W/m²K] | τ [s] | to within 2 K of room [min] | Bi |",
      "|---|---|---|---|---|---|"]
hr = float(h_radiation(0.3, T_mid, T_INF))
rows = [("still air", float(h_free_horizontal_cylinder(D, np.array([T_mid]), T_INF, ATM)[0]))]
rows += [(f"fan {U:g} m/s", h_forced_cylinder(D, U, T_mid, T_INF, ATM, "churchill_bernstein"))
         for U in (1.0, 2.0, 3.0)]
for name, hc in rows:
    ht = hc + hr
    tau = C_per_A / ht
    L.append(f"| {name} | {hc:.1f} | {ht:.1f} | {tau:.0f} | {tau * np.log(75 / 2) / 60:.1f} "
             f"| {ht * D / 4 / mat.k:.1e} |")

# ------------------------------------------------------------------ Week 2
D_F = float(d_fuller("ethanol", "air", T_INF, ATM))
D_CE = float(d_chapman_enskog("ethanol", "air", T_INF, ATM))
y_s = ETHANOL.psat(T_INF) / ATM
L += ["", "## Week 2: ethanol evaporation", "",
      f"- D_AB ethanol-air at 25 °C: Fuller {D_F:.3e}, Chapman-Enskog {D_CE:.3e} m²/s",
      f"- P_sat(25 °C) = {ETHANOL.psat(T_INF) / 1e3:.2f} kPa (y_s = {y_s:.3f}); "
      f"P_sat(10 °C) = {ETHANOL.psat(c_to_k(10)) / 1e3:.2f} kPa",
      f"- dew point of 25 °C air at 60 % / 70 % RH: {dew_point(0.6, T_INF, ATM) - 273.15:.1f} / "
      f"{dew_point(0.7, T_INF, ATM) - 273.15:.1f} °C", ""]

R_d, m0 = 0.045, 20e-6 * ETHANOL.rho(T_INF)
amb = ev.Ambient(T_INF, T_INF, ATM, 0.0)
diff = ev.Diffusivities(lambda T: float(d_fuller("ethanol", "air", T, ATM)),
                        lambda T: float(d_fuller("water", "air", T, ATM)))
dish = ev.Dish(R_d, 0.0, 0.0, 0.0, 0.95)  # flush, no conduction through the bottom
A = dish.area
L += [f"Open dish {2 * R_d * 100:g} cm across, liquid level with the rim, 20 mL ({m0 * 1e3:.1f} g) of "
      "ethanol, dry air, radiation ε = 0.95, no heat from the table (upper bound on cooling).", "",
      "| condition | k_c [mm/s] | liquid T steady [°C] | rate [g/h] | rate if liquid at 25 °C [g/h] | 20 mL dries in [h] |",
      "|---|---|---|---|---|---|"]
models = [("still air (stable layer)", ev.FreeConvectionSurface(dish.L_char, 1.0, "raise"))]
models += [(f"fan {U:g} m/s", ev.ForcedFlatPlate(U, 2 * R_d, 1.0)) for U in (1.0, 2.0, 3.0)]
models += [("pure diffusion (lower bound)", ev.DiffusionLimitDisk(R_d))]
for name, mdl in models:
    Tw = ev.wet_bulb_temperature(dish, amb, mdl, diff, Ideal(), "none")
    s_w = ev.surface_state(1.0, 0.0, Tw, 0.0, dish, amb, mdl, diff, Ideal(), False, "none")
    s_i = ev.surface_state(1.0, 0.0, T_INF, 0.0, dish, amb, mdl, diff, Ideal(), False, "none")
    r_w, r_i = A * s_w.N_E * ETHANOL.M, A * s_i.N_E * ETHANOL.M
    L.append(f"| {name} | {s_w.kc_E * 1e3:.2f} | {Tw - 273.15:.1f} | {r_w * 3.6e6:.2f} "
             f"| {r_i * 3.6e6:.2f} | {m0 / r_w / 3600:.1f} |")

c, c_L = ATM / (R * T_INF), ETHANOL.rho(T_INF) / ETHANOL.M
K = stefan.stefan_slope(c, c_L, D_F, y_s, 0.0)
L += ["", f"Stefan tube at 25 °C (Fuller D). K = {K:.2e} m²/s in z² - z0² = K t; "
      f"c/c_L = {c / c_L:.4f}, so the pseudo-steady assumption holds.", "",
      "| inner diameter [mm] | z0 [cm] | rate [g/h] | level drop [mm/h] | drop in 24 h [mm] |",
      "|---|---|---|---|---|"]
for d_mm, z0 in ((12, 0.03), (12, 0.05), (16, 0.03), (16, 0.05)):
    At = np.pi * (d_mm * 1e-3) ** 2 / 4
    N = stefan.stefan_flux(c, D_F, z0, y_s, 0.0)
    drop24 = np.sqrt(z0**2 + K * 86400) - z0
    L.append(f"| {d_mm} | {z0 * 100:g} | {N * At * ETHANOL.M * 3.6e6:.3f} "
             f"| {N / c_L * 3.6e6:.2f} | {drop24 * 1e3:.1f} |")

out = Path("docs/design_estimates.md")
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
